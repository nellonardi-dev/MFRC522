	// MFRC522 commands. Described in chapter 10 of the datasheet.
enum RC522_Driver_Command : uint8_t {
		PCD_Idle				= 0x00,		// no action, cancels current command execution
		PCD_Mem					= 0x01,		// stores 25 bytes into the internal buffer
		PCD_GenerateRandomID	= 0x02,		// generates a 10-byte random ID number
		PCD_CalcCRC				= 0x03,		// activates the CRC coprocessor or performs a self-test
		PCD_Transmit			= 0x04,		// transmits data from the FIFO buffer
		PCD_NoCmdChange			= 0x07,		// no command change, can be used to modify the CommandReg register bits without affecting the command, for example, the PowerDown bit
		PCD_Receive				= 0x08,		// activates the receiver circuits
		PCD_Transceive 			= 0x0C,		// transmits data from FIFO buffer to antenna and automatically activates the receiver after transmission
		PCD_MFAuthent 			= 0x0E,		// performs the MIFARE standard authentication as a reader
		PCD_SoftReset			= 0x0F		// resets the MFRC522
};

// MFRC522 RxGain[2:0] masks, defines the receiver's signal voltage gain factor (on the PCD).
// Described in 9.3.3.6 / table 98 of the datasheet at http://www.nxp.com/documents/data_sheet/MFRC522.pdf
enum PCD_RxGain : byte {
	RxGain_18dB				= 0x00 << 4,	// 000b - 18 dB, minimum
	RxGain_23dB				= 0x01 << 4,	// 001b - 23 dB
	RxGain_18dB_2			= 0x02 << 4,	// 010b - 18 dB, it seems 010b is a duplicate for 000b
	RxGain_23dB_2			= 0x03 << 4,	// 011b - 23 dB, it seems 011b is a duplicate for 001b
	RxGain_33dB				= 0x04 << 4,	// 100b - 33 dB, average, and typical default
	RxGain_38dB				= 0x05 << 4,	// 101b - 38 dB
	RxGain_43dB				= 0x06 << 4,	// 110b - 43 dB
	RxGain_48dB				= 0x07 << 4,	// 111b - 48 dB, maximum
	RxGain_min				= 0x00 << 4,	// 000b - 18 dB, minimum, convenience for RxGain_18dB
	RxGain_avg				= 0x04 << 4,	// 100b - 33 dB, average, convenience for RxGain_33dB
	RxGain_max				= 0x07 << 4		// 111b - 48 dB, maximum, convenience for RxGain_48dB
};

enum StatusCode : uint8_t {
    STATUS_OK      = 0x01,
    STATUS_TIMEOUT = 0x02,
    STATUS_ERROR   = 0x03,
    STATUS_COLLISION,
    STATUS_NO_ROOM
};

class RC522_Driver {
private:
    // --------------------------------------------------
    // Hardware
    // --------------------------------------------------
    uint8_t _ssPin;
    uint8_t _resetPin;
    SPIClass* _spi;

    // --------------------------------------------------
    // Accesso ai registri
    // --------------------------------------------------
    void writeRegister(uint8_t reg, uint8_t value);

    void writeRegisterMultiple(
        uint8_t reg,
        const uint8_t* values,
        uint8_t count
    );

    uint8_t readRegister(uint8_t reg);

    void readRegisterMultiple(
        uint8_t reg,
        uint8_t* values,
        uint8_t count
    );

    // --------------------------------------------------
    // FIFO
    // --------------------------------------------------
	void writeFIFO(const uint8_t* data, uint8_t length);
	StatusCode readFIFO(
	    uint8_t* data,
	    uint8_t capacity,
	    uint8_t* length
	);	

	// --------------------------------------------------
    // Set Timer
    // --------------------------------------------------
    void configureTimer();

public:
    // --------------------------------------------------
    // Velocità supportate dal MFRC522
    // --------------------------------------------------
    enum BaudRate : uint8_t {
        BAUD_106KBPS = 0,
        BAUD_212KBPS = 1,
        BAUD_424KBPS = 2,
        BAUD_848KBPS = 3
    };

    // --------------------------------------------------
    // Costruttore e inizializzazione
    // --------------------------------------------------
    RC522_Driver(
        uint8_t ssPin,
        uint8_t resetPin = 255,
        SPIClass& spi = SPI
    );

    void begin();
    void reset();

    // --------------------------------------------------
    // Identificazione e diagnostica
    // --------------------------------------------------
    uint8_t getVersion();
    bool selfTest();
    void printRFRegisters();

    // --------------------------------------------------
    // Configurazione hardware RF
    // --------------------------------------------------
    void configureRF(
        uint8_t txMode,
        uint8_t rxMode,
        uint8_t txASK,
        uint8_t modWidth,
        uint8_t modeReg
    );

    void setBaudRate(BaudRate rate);
    void setModulation(bool ask100);
    void setCRCMode(uint8_t preset);

    // --------------------------------------------------
    // Antenna e ricevitore
    // --------------------------------------------------
    void setAntenna(bool enabled);
    void setAntennaGain(PCD_RxGain gain);
    PCD_RxGain getAntennaGain();

    // --------------------------------------------------
    // Funzioni hardware di comunicazione
    // --------------------------------------------------
    StatusCode calculateCRC(
        const uint8_t* data,
        uint8_t length,
        uint8_t* result
    );

    StatusCode transceiveData(
        const uint8_t* sendData,
        uint8_t sendLen,
        uint8_t* recvData,
        uint8_t* recvLen,
        uint8_t recvCapacity,
        uint8_t txLastBits = 0,
        uint8_t rxAlign = 0,
        uint8_t* rxLastBits = nullptr,
        uint8_t* collisionPos = nullptr,
        bool checkCRC = false
    );

    // --------------------------------------------------
    // Diagnostica registri
    // --------------------------------------------------
    uint8_t peekRegister(uint8_t reg);
};

